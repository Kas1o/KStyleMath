namespace KStyleMath;

public static class SymbolsSpacingFunctions
{
    // A map of CSS-based spacing functions to their CSS class.
    private static readonly Dictionary<string, string> CssSpace = new(StringComparer.Ordinal)
    {
        ["\\nobreak"] = "nobreak",
        ["\\allowbreak"] = "allowbreak",
    };

    // A lookup table to determine whether a spacing function/symbol should be
    // treated like a regular space character.  If a symbol or command is a key
    // in this table, then it should be a regular space character.  Furthermore,
    // the associated value may have a `className` specifying an extra CSS class
    // to add to the created `span`.
    private static readonly Dictionary<string, string> RegularSpace = new(StringComparer.Ordinal)
    {
        [" "] = null,
        ["\\ "] = null,
        ["~"] = "nobreak",
        ["\\space"] = null,
        ["\\nobreakspace"] = "nobreak",
    };

    public static void Define()
    {
        // ParseNode<"spacing"> created in Parser.js from the "spacing" symbol Groups in
        // src/symbols.js.
        Registries.DefineFunctionBuilders(
            "spacing",
            (group, options) =>
            {
                bool hasRegularSpace = RegularSpace.TryGetValue(
                    group.Str("text"), out var regularSpaceClass);
                bool hasCssSpace = CssSpace.TryGetValue(
                    group.Str("text"), out var cssSpaceClass);

                if (hasRegularSpace)
                {
                    var className = regularSpaceClass ?? "";
                    // Spaces are generated by adding an actual space. Each of these
                    // things has an entry in the symbols table, so these will be turned
                    // into appropriate outputs.
                    if (group.Mode == "text")
                    {
                        var ord = BuildCommon.MakeOrd(group, options);
                        ord.Classes.Add(className);
                        return ord;
                    }
                    else
                    {
                        return BuildCommon.MakeSpan(
                            new List<string> { "mspace", className },
                            new List<VirtualNode>
                            {
                                BuildCommon.Mathsym(group.Str("text"), group.Mode, options),
                            },
                            options);
                    }
                }
                else if (hasCssSpace)
                {
                    // Spaces based on just a CSS class.
                    return BuildCommon.MakeSpan(
                        new List<string> { "mspace", cssSpaceClass },
                        new List<VirtualNode>(), options);
                }
                else
                {
                    throw new ParseError($"Unknown type of space \"{group.Str("text")}\"");
                }
            },
            (group, options) =>
            {
                MathNode node;

                if (RegularSpace.ContainsKey(group.Str("text")))
                {
                    node = new MathNode(
                        "mtext",
                        new List<VirtualNode> { new MathTextNode("\u00a0") });
                }
                else if (CssSpace.ContainsKey(group.Str("text")))
                {
                    // CSS-based MathML spaces (\nobreak, \allowbreak) are ignored
                    return new MathNode("mspace");
                }
                else
                {
                    throw new ParseError($"Unknown type of space \"{group.Str("text")}\"");
                }

                return node;
            });
    }
}
